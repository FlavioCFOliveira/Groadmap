// sweepToolExclusions reads the repository's tool configuration and returns
// every path some tool is told to skip, deduplicated and sorted. A configuration
// file that cannot be read fails the test: a silent read error would shrink the
// sweep to nothing and take the gate with it.
func sweepToolExclusions(t *testing.T, root string) []toolExclusion {
	t.Helper()

	found := map[string]string{} // path -> source

	for _, rel := range toolConfigFiles {
		content, err := os.ReadFile(filepath.Clean(filepath.Join(root, filepath.FromSlash(rel))))
		if err != nil {
			t.Fatalf("reading the tool configuration file %s: %v", rel, err)
		}
		text := string(content)

		for _, match := range excludeDirPattern.FindAllStringSubmatch(text, -1) {
			path := normaliseExclusionPath(match[1])
			if path == "" {
				continue
			}
			if _, seen := found[path]; !seen {
				found[path] = rel + ": -exclude-dir=" + match[1]
			}
		}

		if rel == ".golangci.yml" {
			for _, path := range golangciExcludedPaths(text) {
				if _, seen := found[path]; !seen {
					found[path] = rel + ": an entry under `paths:`"
				}
			}
		}
	}

	paths := make([]string, 0, len(found))
	for path := range found {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	exclusions := make([]toolExclusion, 0, len(paths))
	for _, path := range paths {
		exclusions = append(exclusions, toolExclusion{path: path, source: found[path]})
	}
	return exclusions
}

// golangciRegexMeta are the regular-expression characters that turn a
// golangci-lint `paths:` entry into a shape rather than a path. A leading ^ and
// a trailing $ are stripped before this check, so an entry still carrying any of
// these is a pattern and is skipped.
//
// "." is deliberately absent. It is a regex metacharacter, but in a path it is
// overwhelmingly a literal — ".claude" is the entry this whole gate turns on —
// and treating it as a pattern made the sweep skip the very directory the
// defect lives under. An entry that really is a regex reaches for "\." instead,
// and the backslash IS in this set.
const golangciRegexMeta = `\*?[]()|+{}^$`

// golangciExcludedPaths returns the plain directory paths named by the
// `paths:` lists in a .golangci.yml document. It is a targeted scan rather than
// a YAML parse: the module has no YAML dependency, and this gate must not add
// one to read five list items.
func golangciExcludedPaths(document string) []string {
	lines := strings.Split(document, "\n")
	paths := make([]string, 0, len(lines))

	for index, line := range lines {
		if strings.TrimSpace(line) != "paths:" {
			continue
		}
		keyIndent := len(line) - len(strings.TrimLeft(line, " "))

		for _, item := range lines[index+1:] {
			trimmed := strings.TrimSpace(item)
			if trimmed == "" {
				break
			}
			itemIndent := len(item) - len(strings.TrimLeft(item, " "))
			if itemIndent <= keyIndent || !strings.HasPrefix(trimmed, "- ") {
				break
			}

			value := strings.Trim(strings.TrimSpace(strings.TrimPrefix(trimmed, "- ")), `"'`)
			value = strings.TrimSuffix(strings.TrimPrefix(value, "^"), "$")
			if value == "" || strings.ContainsAny(value, golangciRegexMeta) {
				continue
			}
			if path := normaliseExclusionPath(value); path != "" {
				paths = append(paths, path)
			}
		}
	}
	return paths
}

// makefileCleanOperands returns the paths the Makefile's `clean` target deletes,
// relative to the module root.
func makefileCleanOperands(t *testing.T) []string {
	t.Helper()

	lines := strings.Split(readRepoFileAt(t, "Makefile"), "\n")

	start := -1
	for index, line := range lines {
		if strings.HasPrefix(line, "clean:") {
			start = index
			break
		}
	}
	if start < 0 {
		t.Fatal("the Makefile declares no `clean` target, so this gate cannot read what the build leaves behind")
	}

	operands := make([]string, 0, len(lines))
	for _, line := range lines[start+1:] {
		if !strings.HasPrefix(line, "\t") {
			break
		}
		fields := strings.Fields(strings.TrimPrefix(line, "\t"))
		if len(fields) == 0 || strings.TrimPrefix(fields[0], "@") != "rm" {
			continue
		}
		for _, field := range fields[1:] {
			if strings.HasPrefix(field, "-") {
				continue
			}
			if path := normaliseExclusionPath(field); path != "" {
				operands = append(operands, path)
			}
		}
	}

	sort.Strings(operands)
	return operands
}

// registerCovers reports whether generatedPaths accounts for a path: either as
// that exact file, or as a directory the path lies within.
func registerCovers(path string) bool {
	for _, generated := range generatedPaths {
		if !strings.HasSuffix(generated.path, "/") {
			if generated.path == path {
				return true
			}
			continue
		}
		if strings.HasPrefix(path+"/", generated.path) {
			return true
		}
	}
	return false
}

// normaliseExclusionPath reduces a path as it is written in a configuration file
// to the slash-separated, module-root-relative form the rest of this file uses:
// no "./" prefix, no "$(CURDIR)/" prefix, no trailing slash.
func normaliseExclusionPath(raw string) string {
	path := strings.TrimSpace(raw)
	path = strings.TrimPrefix(path, "$(CURDIR)/")
	path = strings.TrimPrefix(path, "./")
	path = strings.TrimSuffix(path, "/")
	if path == "." || path == ".." {
		return ""
	}
	return path
}

