// gitIn runs git in dir and returns its combined output with the trailing
// newline removed.
func gitIn(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return strings.TrimRight(string(out), "\n"), err
}

// gitCheckIgnore reports which ignore rule covers path, as git itself resolves
// it: the source file of the winning rule and the rule's pattern. Both are empty
// when nothing ignores the path.
//
// The index is deliberately consulted (no --no-index), because that is what
// `git status` does: a tracked path is never reported as ignored, which is the
// distinction that makes TestGeneratedPathsAreIgnoredByThisRepositorysOwnRules
// meaningful for a path someone committed before the rule existed.
func gitCheckIgnore(t *testing.T, root, path string) (source, rule string) {
	t.Helper()

	cmd := exec.Command("git", "check-ignore", "--verbose", "--", path)
	cmd.Dir = root
	out, err := cmd.Output()
	text := strings.TrimRight(string(out), "\n")

	if err != nil {
		var exitErr *exec.ExitError
		if errors.As(err, &exitErr) && exitErr.ExitCode() == 1 {
			return "", "" // git's answer for "no rule covers this path"
		}
		t.Fatalf("git check-ignore --verbose -- %s: %v\n%s", path, err, text)
	}

	line, _, _ := strings.Cut(text, "\n")
	field, _, found := strings.Cut(line, "\t")
	if !found {
		t.Fatalf("git check-ignore reported %q for %s, which is not the documented "+
			"<source>:<line>:<pattern>\\t<path> form", line, path)
	}
	parts := strings.SplitN(field, ":", 3)
	if len(parts) != 3 {
		t.Fatalf("git check-ignore reported %q for %s, which is not the documented "+
			"<source>:<line>:<pattern> form", field, path)
	}
	return parts[0], parts[2]
}

// trackedFilesUnder lists the files git tracks under a module-root-relative
// path. An empty result is the proof that an ignore rule is not covering for
// something already in the index.
func trackedFilesUnder(t *testing.T, root, path string) []string {
	t.Helper()

	out, err := gitIn(root, "ls-files", "--", path)
	if err != nil {
		t.Fatalf("git ls-files -- %s: %v\n%s", path, err, out)
	}
	if out == "" {
		return nil
	}
	return strings.Split(out, "\n")
}

// statusEntries returns the porcelain status of the working tree as a set.
// --untracked-files=all expands an ordinary untracked directory into its files,
// so nothing hides behind a collapsed entry; a directory holding its own .git,
// as a linked worktree does, is one entry either way, and one entry is already
// one too many.
func statusEntries(t *testing.T, root string) map[string]bool {
	t.Helper()

	out, err := gitIn(root, "status", "--porcelain", "--untracked-files=all")
	if err != nil {
		t.Fatalf("git status --porcelain --untracked-files=all: %v\n%s", err, out)
	}

	entries := map[string]bool{}
	if out == "" {
		return entries
	}
	for _, line := range strings.Split(out, "\n") {
		entries[line] = true
	}
	return entries
}
